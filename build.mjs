import fs from "fs";
import path from "path";
import esbuild from "esbuild";

const root = path.dirname(new URL(import.meta.url).pathname);
const watch = process.argv.includes("--watch");

// ---------------------------------------------------------------------------
// 1. pdf.js worker, inlined as base64 into a Blob URL.
//    Obsidian only downloads main.js / manifest.json / styles.css when a
//    plugin is installed from the community directory, so every runtime asset
//    has to live inside main.js.
// ---------------------------------------------------------------------------
const workerPath = path.join(root, "node_modules/pdfjs-dist/legacy/build/pdf.worker.min.js");
const b64 = fs.readFileSync(workerPath).toString("base64");
fs.writeFileSync(
  path.join(root, "src/worker-b64.ts"),
  "// generated by build.mjs - do not edit\nexport const PDF_WORKER_B64 = " + JSON.stringify(b64) + ";\n"
);
console.log("worker inlined:", (b64.length / 1024 / 1024).toFixed(2), "MB base64");

// ---------------------------------------------------------------------------
// 2. CJK CMap tables + standard font data, also inlined.
//    Without them, PDFs that use predefined CJK CMaps (very common in
//    Chinese/Japanese/Korean documents) lose their text layer, so text
//    selection silently stops working. LICENSE* files are skipped here and
//    attributed in THIRD-PARTY-NOTICES.md instead.
// ---------------------------------------------------------------------------
function collect(dir, filter) {
  const out = {};
  if (!fs.existsSync(dir)) return out;
  for (const name of fs.readdirSync(dir).sort()) {
    const abs = path.join(dir, name);
    if (!fs.statSync(abs).isFile()) continue;
    if (/^LICENSE/i.test(name)) continue;
    if (!filter.test(name)) continue;
    out[name] = fs.readFileSync(abs).toString("base64");
  }
  return out;
}

const cmaps = {};
for (const [name, b] of Object.entries(
  collect(path.join(root, "node_modules/pdfjs-dist/cmaps"), /\.bcmap$/i)
)) {
  cmaps[name.replace(/\.bcmap$/i, "")] = b;
}
const fonts = collect(path.join(root, "node_modules/pdfjs-dist/standard_fonts"), /\.(pfb|ttf|otf)$/i);

const bytes = (o) => Object.values(o).reduce((n, s) => n + s.length, 0);
console.log(
  "resources inlined:",
  Object.keys(cmaps).length,
  "CMaps,",
  Object.keys(fonts).length,
  "fonts,",
  (bytes(cmaps) + bytes(fonts)) / 1024 / 1024,
  "MB base64"
);

fs.writeFileSync(
  path.join(root, "src/pdfres-b64.ts"),
  "// generated by build.mjs - do not edit\n" +
    "export const CMAP_DATA: Record<string, string> = " +
    JSON.stringify(cmaps) +
    ";\n\n" +
    "export const FONT_DATA: Record<string, string> = " +
    JSON.stringify(fonts) +
    ";\n"
);

// ---------------------------------------------------------------------------
// 3. Remove the parts of pdf.js that the community directory's automated
//    review flags as "code that can run dynamic code": a <script> injector,
//    a new Function("") feature probe, and the Node-only eval("require") path.
//
//    None of them can be reached in PDFmark, because the worker, the CMap
//    tables and the standard fonts are all inlined and handed to pdf.js as
//    in-memory data. Removing them is therefore behaviour-preserving — and
//    it is not cosmetic: an unreachable <script> tag is still an error that
//    blocks installation from inside Obsidian.
// ---------------------------------------------------------------------------
const stripPdfjsDynamicCode = {
  name: "pdfjs-strip-dynamic-code",
  setup(build) {
    build.onLoad({ filter: /pdfjs-dist[\\/]legacy[\\/]build[\\/]pdf\.js$/ }, async (args) => {
      let src = await fs.promises.readFile(args.path, "utf8");

      // loadScript(): appends a <script src> to the document to pull in a
      // worker or a CMap table from a URL. Inlined here, so it never runs.
      src = src.replace(
        /function loadScript\(src\) \{[\s\S]*?\n\}/,
        "function loadScript(src) {\n" +
          "  return Promise.reject(new Error(`PDFmark inlines its worker and fonts; refusing to load ${src}.`));\n" +
          "}"
      );

      // isEvalSupported(): probe for new Function(""), used only to choose a
      // faster glyph compiler. Reporting false is a documented fallback.
      src = src.replace(
        /function isEvalSupported\(\) \{[\s\S]*?\n\}/,
        "function isEvalSupported() {\n  return false;\n}"
      );

      // eval("require") is the Node branch that loads the worker from disk.
      src = src.replace(
        'eval("require")(this.workerSrc)',
        '(() => { throw new Error("PDFmark runs its worker from the inlined bundle."); })()'
      );

      // getPathGenerator() compiles glyph outlines to a function body and
      // instantiates it when eval is available. The isEvalSupported check above
      // now reports false, so this branch is already dead; forcing the
      // condition to false lets the minifier drop the new Function call itself,
      // which keeps it out of the reach of a static scan. The interpreter on the
      // next line does the same work and is pdf.js's own fallback.
      src = src.replace(
        "if (this.isEvalSupported && _util.FeatureTest.isEvalSupported) {",
        "if (false) {"
      );

      for (const needle of ['createElement("script")', 'new Function("")', 'eval("require")', "eval("]) {
        if (src.includes(needle)) {
          throw new Error("pdfjs patch missed \"" + needle + "\" - pdfjs-dist was probably upgraded");
        }
      }
      return { contents: src, loader: "js" };
    });
  },
};

const pkg = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
const repoUrl = (pkg.repository && pkg.repository.url ? pkg.repository.url : "").replace(/\.git$/, "");
const banner =
  "/*! PDFmark v" +
  pkg.version +
  " | MIT License" +
  (repoUrl ? " | " + repoUrl : "") +
  "\n" +
  " *  Bundles pdf.js (Apache-2.0, (c) Mozilla and contributors) and pdf-lib (MIT).\n" +
  " *  CMap tables and standard font data are part of pdfjs-dist.\n" +
  " *  See THIRD-PARTY-NOTICES.md for the full license texts. */";

const options = {
  entryPoints: [path.join(root, "src/main.ts")],
  bundle: true,
  outfile: path.join(root, "main.js"),
  format: "cjs",
  platform: "browser",
  target: ["es2018"],
  external: ["obsidian", "electron", "canvas"],
  logLevel: "info",
  sourcemap: false,
  minify: !watch,
  // Keep license / attribution comments that third-party code carries.
  legalComments: "eof",
  banner: { js: banner },
  define: { "process.env.NODE_ENV": JSON.stringify("production") },
  plugins: [stripPdfjsDynamicCode],
};

if (watch) {
  const ctx = await esbuild.context(options);
  await ctx.watch();
  console.log("watching...");
} else {
  await esbuild.build(options);
  console.log("build ok ->", path.join(root, "main.js"));
}
